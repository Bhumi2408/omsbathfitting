// Rough reading time from every text string in the post (~200 wpm).
export function readingTime(blog) {
  const strings = [];
  const collect = (value, key) => {
    if (typeof value === "string") {
      if (key !== "type" && key !== "id") strings.push(value);
    } else if (Array.isArray(value)) {
      value.forEach((v) => collect(v));
    } else if (value && typeof value === "object") {
      Object.entries(value).forEach(([k, v]) => collect(v, k));
    }
  };
  collect([blog.content, blog.faqs]);
  const words = strings.join(" ").split(/\s+/).filter(Boolean).length;
  return Math.max(1, Math.round(words / 200));
}

export function formatDate(iso) {
  return new Date(iso).toLocaleDateString("en-IN", {
    day: "numeric",
    month: "long",
    year: "numeric",
  });
}
